CREATE TABLE company_billing_rule (
  company_billing_rule_id  integer GENERATED BY DEFAULT AS IDENTITY,
  company_number           varchar(20)  NOT NULL,
  company_share_percent    numeric      NOT NULL,
  employee_share_percent   numeric      NOT NULL,
  effective_date           date         NOT NULL,
  active                   boolean      NOT NULL,
  notes                    text,
  created_at               timestamptz  DEFAULT now(),
  CONSTRAINT company_billing_rule_pk PRIMARY KEY (company_billing_rule_id),
  CONSTRAINT company_billing_rule_company_date_uq UNIQUE (company_number, effective_date)
);

CREATE TABLE enrollment_status_history (
  status_history_id        integer GENERATED BY DEFAULT AS IDENTITY,
  entity_type              varchar(20)   NOT NULL,
  entity_id                integer       NOT NULL,
  member_id                integer,
  company_number           varchar(20),
  person_identifier        varchar(100),
  person_name              varchar(180)  NOT NULL,
  old_active               boolean       NOT NULL,
  new_active               boolean       NOT NULL,
  effective_date           date          NOT NULL,
  reason                   text          NOT NULL,
  cascade_applied          boolean       NOT NULL,
  related_records_changed  integer,
  changed_at               timestamptz,
  changed_by               varchar(100),
  notes                    text,
  CONSTRAINT enrollment_status_history_pk PRIMARY KEY (status_history_id)
);
CREATE INDEX enrollment_status_history_effective_date_idx ON enrollment_status_history (effective_date);
CREATE INDEX enrollment_status_history_entity_idx         ON enrollment_status_history (entity_type, entity_id);
CREATE INDEX enrollment_status_history_member_id_idx      ON enrollment_status_history (member_id);

CREATE TABLE import_exception (
  exception_id       integer GENERATED BY DEFAULT AS IDENTITY,
  source_alias       varchar(255),
  source_file        varchar(255),
  source_path        text,
  sheet_name         varchar(100),
  excel_row          integer,
  cell_or_range      varchar(255),
  entity_type        varchar(30),
  person_name        varchar(255),
  member_identifier  varchar(100),
  reason_codes       text,
  reason             text,
  required_action    text,
  raw_row_summary    text,
  created_at         timestamptz  DEFAULT now(),
  CONSTRAINT import_exception_pk PRIMARY KEY (exception_id)
);
CREATE INDEX import_exception_source_idx ON import_exception (source_file, sheet_name, excel_row);

