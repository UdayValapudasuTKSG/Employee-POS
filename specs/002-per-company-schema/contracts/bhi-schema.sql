-- =============================================================================
-- Contract: the 11 tables of the BHI Enrollment Database (Access, schema-only
-- file dated 2026-08-28) that the application uses, held once in schema "bhi"
-- and shared by every company. The file's seven other import tables
-- (source_workbook_archive, source_workbook_sheet, raw_enrollment_row,
-- raw_enrollment_cell, import_adjustment, import_reconciliation,
-- import_documentation) were dropped on 2026-09-29: nothing wrote or read them.
--
-- SC-001 compares the live database against this file. Naming and type rules:
-- research.md R2 and R3. Deviations from the Access file: D1-D3 on
-- premium_rates only (spec.md, "Deviations from the Access file").
--
-- Not structure, and so not part of this contract: row-level security policies
-- (research R4), grants (R5) and the FINAL-run / used-rate triggers (R13, R14).
-- They live in the SQL migrations that apply this file.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS bhi;
SET search_path TO bhi;

-- ---------------------------------------------------------------------------
-- Group A: tables in the relationships diagram
-- ---------------------------------------------------------------------------

CREATE TABLE company (
  company_number   varchar(20)  NOT NULL,
  company_name     varchar(120) NOT NULL,
  address1         varchar(120),
  address2         varchar(120),
  city             varchar(80),
  contact_name     varchar(100),
  contact_phone    varchar(50),
  contact_email    varchar(100),
  active           boolean      NOT NULL,
  notes            text,
  created_at       timestamptz  DEFAULT now(),
  updated_at       timestamptz  DEFAULT now(),
  CONSTRAINT company_pk PRIMARY KEY (company_number)
);
CREATE INDEX company_active_idx ON company (active);

CREATE TABLE class (
  class_code   varchar(1)   NOT NULL,
  class_name   varchar(50)  NOT NULL,
  description  varchar(255),
  active       boolean      NOT NULL,
  sort_order   integer,
  CONSTRAINT class_pk PRIMARY KEY (class_code)
);

CREATE TABLE member (
  member_id        integer GENERATED BY DEFAULT AS IDENTITY,
  id_type          varchar(20)   NOT NULL,
  id_number        varchar(40)   NOT NULL,
  company_number   varchar(20)   NOT NULL,
  last_name        varchar(80)   NOT NULL,
  first_name       varchar(80)   NOT NULL,
  middle_initials  varchar(20),
  date_of_birth    date,
  sex              varchar(10),
  class_code       varchar(1)    NOT NULL,
  address_line1    varchar(150),
  address_line2    varchar(150),
  phone            varchar(50),
  email            varchar(100),
  employment_date  date,
  plan_date        date,
  rate_of_pay      numeric(15,2),
  occupation       varchar(100),
  active           boolean       NOT NULL,
  inactive_date    date,
  inactive_reason  text,
  notes            text,
  created_at       timestamptz   DEFAULT now(),
  updated_at       timestamptz   DEFAULT now(),
  CONSTRAINT member_pk PRIMARY KEY (member_id),
  CONSTRAINT member_id_type_id_number_uq UNIQUE (id_type, id_number),
  -- R1
  CONSTRAINT member_company_fk FOREIGN KEY (company_number)
    REFERENCES company (company_number) ON UPDATE CASCADE ON DELETE RESTRICT,
  -- R6
  CONSTRAINT member_class_fk FOREIGN KEY (class_code)
    REFERENCES class (class_code) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX member_active_idx         ON member (active);
CREATE INDEX member_class_code_idx     ON member (class_code);
CREATE INDEX member_company_number_idx ON member (company_number);

CREATE TABLE dependent (
  dependent_id         integer GENERATED BY DEFAULT AS IDENTITY,
  member_id            integer       NOT NULL,
  id_type              varchar(20),
  id_number            varchar(40),
  dependent_full_name  varchar(120)  NOT NULL,
  date_of_birth        date,
  sex                  varchar(10),
  relationship         varchar(30)   NOT NULL,
  active               boolean       NOT NULL,
  inactive_date        date,
  inactive_reason      text,
  notes                text,
  created_at           timestamptz   DEFAULT now(),
  updated_at           timestamptz   DEFAULT now(),
  CONSTRAINT dependent_pk PRIMARY KEY (dependent_id),
  -- R4
  CONSTRAINT dependent_member_fk FOREIGN KEY (member_id)
    REFERENCES member (member_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX dependent_active_idx            ON dependent (active);
CREATE INDEX dependent_id_type_id_number_idx ON dependent (id_type, id_number);
CREATE INDEX dependent_member_id_idx         ON dependent (member_id);

CREATE TABLE beneficiary (
  beneficiary_id         integer GENERATED BY DEFAULT AS IDENTITY,
  member_id              integer       NOT NULL,
  id_type                varchar(20),
  id_number              varchar(40),
  beneficiary_full_name  varchar(120)  NOT NULL,
  date_of_birth          date,
  sex                    varchar(10),
  relationship           varchar(30),
  phone                  varchar(50),
  email                  varchar(100),
  share_percent          numeric,
  active                 boolean       NOT NULL,
  inactive_date          date,
  inactive_reason        text,
  notes                  text,
  created_at             timestamptz   DEFAULT now(),
  updated_at             timestamptz   DEFAULT now(),
  CONSTRAINT beneficiary_pk PRIMARY KEY (beneficiary_id),
  -- R5
  CONSTRAINT beneficiary_member_fk FOREIGN KEY (member_id)
    REFERENCES member (member_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX beneficiary_active_idx            ON beneficiary (active);
CREATE INDEX beneficiary_id_type_id_number_idx ON beneficiary (id_type, id_number);
CREATE INDEX beneficiary_member_id_idx         ON beneficiary (member_id);

CREATE TABLE premium_rates (
  premium_rate_id   integer GENERATED BY DEFAULT AS IDENTITY,
  company_number    varchar(20),                 -- D1: blank = standard rate
  class_code        varchar(1)     NOT NULL,
  coverage_band     varchar(20)    NOT NULL,
  coverage_label    varchar(80)    NOT NULL,
  dependent_band    smallint       NOT NULL,
  total_premium     numeric(15,2)  NOT NULL,
  company_premium   numeric(15,2)  NOT NULL,
  employee_premium  numeric(15,2)  NOT NULL,
  effective_date    date           NOT NULL,
  active            boolean        NOT NULL,
  notes             text,
  created_at        timestamptz    DEFAULT now(),
  CONSTRAINT premium_rates_pk PRIMARY KEY (premium_rate_id),
  -- D2 (PostgreSQL 15+): two standard rates for the same class/tier/date collide
  CONSTRAINT premium_rates_company_class_band_date_uq
    UNIQUE NULLS NOT DISTINCT (company_number, class_code, coverage_band, effective_date),
  -- R7
  CONSTRAINT premium_rates_class_fk FOREIGN KEY (class_code)
    REFERENCES class (class_code) ON UPDATE CASCADE ON DELETE RESTRICT,
  -- R8 (D3)
  CONSTRAINT premium_rates_company_fk FOREIGN KEY (company_number)
    REFERENCES company (company_number) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX premium_rates_active_idx ON premium_rates (active);

CREATE TABLE billing_run (
  billing_run_id  integer GENERATED BY DEFAULT AS IDENTITY,
  company_number  varchar(20)  NOT NULL,
  billing_month   date         NOT NULL,
  billing_date    date         NOT NULL,
  generated_at    timestamptz,
  generated_by    varchar(80),
  status          varchar(20),
  notes           text,
  CONSTRAINT billing_run_pk PRIMARY KEY (billing_run_id),
  -- R2
  CONSTRAINT billing_run_company_fk FOREIGN KEY (company_number)
    REFERENCES company (company_number) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX billing_run_company_month_idx ON billing_run (company_number, billing_month);

CREATE TABLE billing_line (
  billing_line_id         integer GENERATED BY DEFAULT AS IDENTITY,
  billing_run_id          integer        NOT NULL,
  member_id               integer        NOT NULL,
  id_type                 varchar(20)    NOT NULL,
  id_number               varchar(40)    NOT NULL,
  member_name             varchar(180)   NOT NULL,
  company_number          varchar(20)    NOT NULL,
  class_code              varchar(1)     NOT NULL,
  active_dependent_count  integer        NOT NULL,
  coverage_band           varchar(20)    NOT NULL,
  coverage_label          varchar(80)    NOT NULL,
  total_premium           numeric(15,2)  NOT NULL,
  company_premium         numeric(15,2)  NOT NULL,
  employee_premium        numeric(15,2)  NOT NULL,
  rate_effective_date     date           NOT NULL,
  premium_rate_id         integer,
  created_at              timestamptz    DEFAULT now(),
  CONSTRAINT billing_line_pk PRIMARY KEY (billing_line_id),
  -- R3 (the only cascading delete in the model; bhi_app has no DELETE grant,
  -- so no application path can trigger it — research.md R5)
  CONSTRAINT billing_line_run_fk FOREIGN KEY (billing_run_id)
    REFERENCES billing_run (billing_run_id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX billing_line_id_type_id_number_idx ON billing_line (id_type, id_number);
CREATE INDEX billing_line_member_id_idx         ON billing_line (member_id);
CREATE INDEX billing_line_billing_run_id_idx    ON billing_line (billing_run_id);

-- ---------------------------------------------------------------------------
-- Group B: standalone tables (no foreign keys, as in the Access file).
-- Company is traced through public.import_batch (research R4).
