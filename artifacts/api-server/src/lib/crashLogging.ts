import { logger } from "./logger";

/**
 * Makes the process say why it died.
 *
 * This module registers its handlers as a side effect of being imported, and
 * index.ts imports it on the first line, before anything else. That ordering is
 * the whole point and is not stylistic: ES modules evaluate their imports in
 * declaration order before the importing module's own body runs, so anything
 * placed inside a function called later in index.ts would install *after*
 * ./app, ./lib/seed and everything they pull in — including lib/db, which throws
 * on an unset DATABASE_URL while it is still being imported.
 *
 * Why it matters at all: when this process exits, nginx has nothing to proxy to
 * and answers every request — API and portal alike — with `502 Bad Gateway`.
 * That page is generated by nginx and says nothing about the cause, and the
 * usual causes leave no trace of their own:
 *
 *   - an `error` event on an EventEmitter with no listener (the database pool
 *     when Postgres restarts is the one this app actually hits — see dbHealth.ts,
 *     which now listens for exactly that);
 *   - a rejected promise nobody awaited, from a background timer such as the
 *     retirement sweep;
 *   - a throw during startup, before the server ever listened.
 *
 * Node prints something to stderr for each and journald keeps it, but it arrives
 * unstructured and out of band from every other line in the log. Routing it
 * through pino instead means one `journalctl -u bhi-api` shows the last requests
 * served and the reason the process stopped, in order, in one format.
 */

/**
 * Logs and exits, without pretending the process can carry on.
 *
 * Both cases below leave state that cannot be reasoned about — a half-applied
 * write, a released lock, an event loop with no idea what failed. systemd's
 * `Restart=on-failure` restarts a clean process in five seconds, which is a
 * better outcome than an old one continuing to serve from unknown state.
 *
 * The exit code is 1 deliberately: `Restart=on-failure` treats 0 as a successful
 * stop and does not restart it.
 */
function logAndExit(event: string, err: unknown): void {
  logger.fatal(
    { err, event },
    `Process exiting on ${event}. nginx will answer 502 until systemd restarts ` +
      "it (Restart=on-failure, RestartSec=5). The error above is the cause.",
  );
  /**
   * In production pino writes straight to stdout with a synchronous write, so
   * the line is on disk before this returns. In development it goes through the
   * pino-pretty worker thread and flushing is asynchronous, so the very last
   * line can still be lost on exit — an acceptable trade for not leaving a
   * broken process running, and irrelevant on a real server.
   */
  logger.flush?.();
  process.exit(1);
}

process.on("uncaughtException", (err) => {
  logAndExit("uncaughtException", err);
});

/**
 * Registered alongside the above because the two are not interchangeable and
 * the same fault can surface as either. A top-level throw while ES modules are
 * still being evaluated is reported through the promise machinery that drives
 * module loading, not as an uncaught exception — so a missing DATABASE_URL
 * arrives here, while the same error thrown from inside a request arrives above.
 */
process.on("unhandledRejection", (reason) => {
  logAndExit("unhandledRejection", reason);
});

/**
 * Warnings Node normally prints raw to stderr — a growing listener count, a
 * deprecated API. Cheap to route through the logger, and the listener-leak
 * warning in particular is usually the first visible sign of a handle being
 * registered per request rather than once.
 */
process.on("warning", (warning) => {
  logger.warn({ err: warning }, `Node warning: ${warning.name}`);
});
